import AppKit
import SwiftUI
import Quartz

@main struct VerifyUtilities {
    static func check(_ value: Bool, _ message: String) {
        guard value else { print("FAIL: \(message)"); fflush(stdout); exit(2) }
        print("PASS: \(message)"); fflush(stdout)
    }
    @MainActor static func pause(_ seconds: Double = 0.15) async { try? await Task.sleep(nanoseconds: UInt64(seconds * 1_000_000_000)) }
    @MainActor static func wait(_ condition: () -> Bool) async {
        for _ in 0..<100 { if condition() { return }; await pause(0.1) }
        check(false, "asynchronous operation finished within ten seconds")
    }
    @MainActor static func capture(_ window: NSWindow, to url: URL) {
        let host = window.contentView!
        host.layoutSubtreeIfNeeded()
        let bitmap = host.bitmapImageRepForCachingDisplay(in: host.bounds)!
        host.cacheDisplay(in: host.bounds, to: bitmap)
        try! bitmap.representation(using: .png, properties: [:])!.write(to: url)
    }
    @MainActor static func click(_ window: NSWindow, x: Double, top: Double) {
        let point = NSPoint(x: x, y: window.frame.height - top)
        let down = NSEvent.mouseEvent(with: .leftMouseDown, location: point, modifierFlags: [], timestamp: ProcessInfo.processInfo.systemUptime, windowNumber: window.windowNumber, context: nil, eventNumber: 1, clickCount: 1, pressure: 1)!
        let up = NSEvent.mouseEvent(with: .leftMouseUp, location: point, modifierFlags: [], timestamp: ProcessInfo.processInfo.systemUptime + 0.04, windowNumber: window.windowNumber, context: nil, eventNumber: 2, clickCount: 1, pressure: 0)!
        NSApp.postEvent(up, atStart: true); window.sendEvent(down)
    }
    @MainActor static func run(_ output: URL) async throws {
        let root = output.appendingPathComponent("fixtures-" + UUID().uuidString, isDirectory: true)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        let suite = "isla.utilities-test.\(UUID().uuidString)"
        let defaults = UserDefaults(suiteName: suite)!
        defer { defaults.removePersistentDomain(forName: suite) }
        let board = NSPasteboard(name: .init(suite))
        defer { board.releaseGlobally() }
        let pins = root.appendingPathComponent("pins.json")
        let clipboard = ClipboardService(board: board, defaults: defaults, storage: pins)
        func copy(_ text: String, hidden: String? = nil) {
            board.clearContents(); board.setString(text, forType: .string)
            if let hidden { board.setString("", forType: .init(hidden)) }
            clipboard.poll()
        }
        copy("Antes de activar")
        check(clipboard.entries.isEmpty && !clipboard.enabled, "clipboard starts disabled and does not capture old content")
        clipboard.setEnabled(true); clipboard.poll()
        check(clipboard.entries.isEmpty, "activation only observes subsequent copies")
        copy("Nota de prueba para ISLA")
        check(clipboard.entries.count == 1 && clipboard.entries[0].kind == .text, "new text is captured")
        let textID = clipboard.entries[0].id
        copy("Nota de prueba para ISLA")
        check(clipboard.entries.count == 1 && clipboard.entries[0].id == textID, "repeated copies are deduplicated")
        for hidden in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            copy("Contenido marcado privado", hidden: hidden)
            check(clipboard.entries.count == 1, "clipboard excludes \(hidden)")
        }
        copy("https://example.com/isla")
        check(clipboard.entries.first?.kind == .link, "HTTP link is recognized")
        board.clearContents(); board.writeObjects([root as NSURL]); clipboard.poll()
        check(clipboard.entries.count == 2, "file copies do not pollute clipboard history")
        copy(String(repeating: "x", count: 30_001))
        check(clipboard.entries.count == 2, "oversized text is skipped")
        clipboard.togglePin(textID)
        check(FileManager.default.fileExists(atPath: pins.path), "pinning persists locally")
        let loaded = ClipboardService(board: board, defaults: defaults, storage: pins)
        check(loaded.entries.count == 1 && loaded.entries[0].pinned && loaded.entries[0].id == textID, "restart restores only pinned content")
        check((try FileManager.default.attributesOfItem(atPath: pins.path)[.posixPermissions] as? Int) == 0o600, "pinned history is readable only by its owner")
        clipboard.setEnabled(false); copy("Mientras está pausado")
        check(clipboard.entries.count == 2, "paused history captures nothing")
        clipboard.setEnabled(true)
        for i in 0..<30 { copy("Reciente \(i)") }
        check(clipboard.entries.count == 25 && clipboard.entries.contains(where: { $0.id == textID }), "recent history is bounded while preserving pins")
        clipboard.copy(clipboard.entries.first!); clipboard.poll()
        check(clipboard.entries.count == 25, "copying from history does not create a capture loop")
        clipboard.clearRecent()
        check(clipboard.entries.count == 1 && clipboard.entries[0].pinned, "clear recent preserves pins")
        clipboard.remove(textID)
        check(ClipboardService(board: board, defaults: defaults, storage: pins).entries.isEmpty, "removing a pin removes persisted content")
        let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 40, pixelsHigh: 30, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        let color = NSColor(deviceRed: 0.3, green: 0.5, blue: 0.8, alpha: 1)
        for x in 0..<40 { for y in 0..<30 { bitmap.setColor(color, atX: x, y: y) } }
        let png = bitmap.representation(using: .png, properties: [:])!
        board.clearContents(); board.setData(png, forType: .png); clipboard.poll()
        check(clipboard.entries.first?.kind == .image && clipboard.entries.first?.image != nil, "copied image is decoded and retained")
        copy("Una idea para más tarde"); clipboard.togglePin(clipboard.entries[0].id)
        copy("https://example.com/isla")

        let fake = root.appendingPathComponent("shortcuts-fixture")
        let uuid = "12345678-1234-1234-1234-123456789ABC"
        let uuid2 = "ABCDEFAB-1234-1234-1234-123456789ABC"
        let script = """
        #!/bin/sh
        cd "$(dirname "$0")" || exit 8
        if [ "$1" = list ]; then
          if [ -f fail-list ]; then exit 1; fi
          printf '%s\\n' 'Preparar imagen (prueba) (\(uuid))' 'Mi atajo ; $(echo literal) (\(uuid2))'
        else
          printf '%s\\n' "$@" >> arguments.txt
          sleep 0.2
          if [ -f fail-run ]; then exit 1; fi
        fi
        """
        try script.write(to: fake, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: fake.path)
        let shortcuts = ShortcutsService(defaults: defaults, executable: fake.path)
        shortcuts.refresh(); await wait { !shortcuts.loading }
        check(shortcuts.items.count == 2 && shortcuts.items[0].name == "Preparar imagen (prueba)", "shortcut parser preserves parentheses and uses UUIDs")
        check(ShortcutsService.parse("garbage\n\(uuid)\nOne (\(uuid))\nTwo (\(uuid))").count == 1, "invalid shortcut rows and duplicate IDs are excluded")
        let item = shortcuts.items[0]
        shortcuts.toggleFavorite(item)
        check(shortcuts.sorted.first == item && ShortcutsService(defaults: defaults).favorites.contains(item.id), "shortcut favorites persist and sort first")
        let original = root.appendingPathComponent("Archivo de prueba ñ.txt")
        try "Contenido original".write(to: original, atomically: true, encoding: .utf8)
        shortcuts.run(item, input: original); shortcuts.run(shortcuts.items[1])
        check(shortcuts.runningID == item.id, "second shortcut cannot start while one is running")
        await wait { shortcuts.runningID == nil }
        let argv = try String(contentsOf: root.appendingPathComponent("arguments.txt"), encoding: .utf8)
        check(argv == "run\n\(uuid)\n--input-path\n\(original.path)\n", "shortcut receives exact ID and spaced file path as separate arguments")
        check(shortcuts.message?.contains("completado") == true, "shortcut success is visible")
        try Data().write(to: root.appendingPathComponent("fail-run"))
        shortcuts.run(item); await wait { shortcuts.runningID == nil }
        check(shortcuts.message?.contains("no terminó") == true, "shortcut failure is visible")
        shortcuts.run(item, input: root.appendingPathComponent("missing"))
        check(shortcuts.runningID == nil && shortcuts.message?.contains("ya no está") == true, "missing shortcut input is rejected")
        try Data().write(to: root.appendingPathComponent("fail-list"))
        shortcuts.refresh(force: true); await wait { !shortcuts.loading }
        check(shortcuts.message?.contains("cargar") == true && shortcuts.items.count == 2, "refresh failure retains the previous shortcuts")
        try FileManager.default.removeItem(at: root.appendingPathComponent("fail-list"))
        try FileManager.default.removeItem(at: root.appendingPathComponent("fail-run"))
        shortcuts.refresh(force: true); await wait { !shortcuts.loading }
        let timed = try await LocalCommand.run("/bin/sleep", arguments: ["2"], timeout: 0.1)
        check(timed.timedOut && timed.status != 0, "unresponsive helper has a bounded timeout")

        let renamed = try ShelfFileOperation.rename(original, to: "Renombrado ñ ; $.txt")
        let renamedContent = try String(contentsOf: renamed, encoding: .utf8)
        check(!FileManager.default.fileExists(atPath: original.path) && renamedContent == "Contenido original", "rename preserves contents and handles Unicode and punctuation")
        for bad in ["", "..", "a/b", "."] {
            do { _ = try ShelfFileOperation.rename(renamed, to: bad); check(false, "invalid name rejected") }
            catch { check(FileManager.default.fileExists(atPath: renamed.path), "invalid name rejected: \(bad)") }
        }
        let collision = root.appendingPathComponent("existente.txt")
        try "No sobrescribir".write(to: collision, atomically: true, encoding: .utf8)
        do { _ = try ShelfFileOperation.rename(renamed, to: collision.lastPathComponent); check(false, "rename collision rejected") }
        catch { check((try String(contentsOf: collision, encoding: .utf8)) == "No sobrescribir", "rename never overwrites another file") }
        let zip = try await ShelfFileOperation.compress(renamed, to: root.appendingPathComponent("Comprimido.zip"))
        let extracted = root.appendingPathComponent("extracted")
        let archive = try await LocalCommand.run("/usr/bin/ditto", arguments: ["-x", "-k", zip.path, extracted.path])
        let extractedContents = try String(contentsOf: extracted.appendingPathComponent(renamed.lastPathComponent), encoding: .utf8)
        check(archive.status == 0 && extractedContents == "Contenido original", "ZIP restores the original Unicode filename and contents at its root")
        do { _ = try await ShelfFileOperation.compress(renamed, to: zip); check(false, "ZIP collision rejected") }
        catch { check(FileManager.default.fileExists(atPath: zip.path), "ZIP never overwrites a destination") }
        do { _ = try await ShelfFileOperation.compress(root, to: root.appendingPathComponent("inside.zip")); check(false, "recursive ZIP rejected") }
        catch { check(true, "ZIP destination cannot be inside the source directory") }

        let data = IslandData(preview: true, clipboard: clipboard, shortcuts: shortcuts)
        var pointer = NSPoint(x: 7000, y: 4200)
        let coordinator = IslandDisplayCoordinator(data: data, location: { pointer })
        coordinator.reconcile([IslandDisplay(id: 1, frame: NSRect(x: 4000, y: 4000, width: 1512, height: 982), notchWidth: 185, notchHeight: 32), IslandDisplay(id: 2, frame: NSRect(x: 5512, y: 4000, width: 1920, height: 1080))])
        let mac = coordinator.islands[1]!, external = coordinator.islands[2]!
        copy("Copia contextual de prueba")
        await pause(0.7)
        check(!external.model.expanded && !external.panel.isVisible, "new clipboard content never reveals the external island")
        pointer = NSPoint(x: external.display.frame.midX, y: external.display.frame.maxY)
        await pause(0.7)
        check(external.model.tab == .clipboard && external.model.expanded, "top-edge hover opens recent clipboard context on the external display")
        external.model.select(.notes)
        copy("Otra copia durante una nota"); await pause(0.4)
        check(external.model.tab == .notes && external.model.expanded, "copying while open does not steal the selected tab")
        external.model.close(); pointer = NSPoint(x: 7000, y: 4200); await pause(0.6)
        external.model.fileDragInProgress = { true }
        pointer = NSPoint(x: external.display.frame.midX, y: external.display.frame.maxY)
        await pause(0.7)
        check(external.model.tab == .files && external.model.expanded, "file-drag context takes precedence over recent clipboard")
        external.model.fileDragInProgress = { false }
        external.model.files = [renamed, zip, collision]
        capture(external.panel, to: output.appendingPathComponent("bandeja.png"))
        external.model.useInShortcut(renamed)
        check(external.model.shortcutInput == renamed && external.model.tab == .shortcuts, "shelf passes selected file to the shortcuts pane")
        await pause(0.3)
        capture(external.panel, to: output.appendingPathComponent("atajos.png"))
        external.model.close(); pointer = NSPoint(x: 7000, y: 4200); await pause(0.6)
        shortcuts.run(item); await wait { shortcuts.runningID == nil }
        check(!external.panel.isVisible && !external.model.expanded, "shortcut completion leaves the external display hidden")
        pointer = NSPoint(x: mac.display.frame.midX, y: mac.display.frame.maxY)
        await pause(0.7)
        check(mac.model.tab == .clipboard && mac.model.expanded, "the built-in notch also opens contextual clipboard at the exact top edge")
        capture(mac.panel, to: output.appendingPathComponent("portapapeles.png"))
        click(mac.panel, x: 246.5, top: 17); await pause(0.5)
        check(mac.model.tab == .shortcuts && mac.model.expanded, "eighth toolbar button is clickable beside the physical notch")
        click(mac.panel, x: 95, top: 87); await pause(0.1)
        await wait { shortcuts.runningID == nil }
        check(shortcuts.message?.contains("completado") == true, "native shortcut button runs the harmless test shortcut")
        click(mac.panel, x: 216.5, top: 17); await pause(0.4)
        check(mac.model.tab == .clipboard, "seventh toolbar button opens clipboard")
        let expectedCopy = clipboard.sorted.first?.text
        click(mac.panel, x: 130, top: 87); await pause(0.3)
        check(expectedCopy != nil && board.string(forType: .string) == expectedCopy, "native history row copies the selected item to the isolated pasteboard")
        mac.model.select(.files); await pause(0.4)
        mac.model.fileActions.preview(renamed); await pause(1)
        check(QLPreviewPanel.shared()?.isVisible == true && QLPreviewPanel.shared()?.dataSource === mac.model.fileActions && mac.model.interacting, "native Quick Look displays the selected file and protects interaction")
        QLPreviewPanel.shared()?.close(); await pause(0.4)
        check(!mac.model.interacting, "closing Quick Look releases interaction protection")
        NotificationCenter.default.post(name: NSMenu.didBeginTrackingNotification, object: NSMenu())
        pointer = NSPoint(x: 7000, y: 4200); await pause(0.7)
        coordinator.closeOutside(pointer)
        check(mac.model.expanded, "tracking a native menu prevents premature collapse")
        NotificationCenter.default.post(name: NSMenu.didEndTrackingNotification, object: NSMenu())
        await pause(0.7)
        check(!mac.model.expanded && !external.panel.isVisible, "leaving both panels closes them after interaction")
        mac.model.addFiles([renamed], reveal: false)
        check(!mac.model.expanded, "delayed drop completion cannot reopen a closed panel")
        clipboard.setEnabled(false)
        mac.model.select(.notes); mac.model.openFromHover()
        check(mac.model.tab == .notes, "paused clipboard cannot override the remembered tab")
        mac.model.close(); clipboard.setEnabled(true)
        copy("Contexto caducado"); mac.model.select(.notes)
        mac.model.openFromHover(now: Date().addingTimeInterval(30))
        check(mac.model.tab == .notes, "expired clipboard context preserves the remembered tab")
        coordinator.stop(); data.stop()
        print("Utilities verified using a named pasteboard, isolated preferences and harmless shortcut fixtures.")
    }
    @MainActor static func main() {
        let app = NSApplication.shared; app.setActivationPolicy(.accessory)
        let output = URL(fileURLWithPath: CommandLine.arguments[1], isDirectory: true)
        Task { @MainActor in
            do {
                if CommandLine.arguments.contains("--live-list") {
                    let service = ShortcutsService()
                    service.refresh()
                    await wait { !service.loading }
                    check(service.message == nil && !service.items.isEmpty, "real Mac Shortcuts library discovered: \(service.items.count) shortcuts; none executed")
                } else { try await run(output) }
                exit(0)
            }
            catch { print("FAIL: \(error)"); exit(3) }
        }
        app.run()
    }
}
