import AppKit
import CryptoKit

struct ClipboardEntry: Identifiable, Codable {
    enum Kind: String, Codable { case text, link, image }
    let id: UUID
    let kind: Kind
    let text: String?
    let imageData: Data?
    let fingerprint: String
    var capturedAt: Date
    var pinned: Bool
    var title: String { kind == .image ? "Imagen copiada" : String((text ?? "").split(whereSeparator: \.isNewline).joined(separator: " ").prefix(160)) }
    var symbol: String { kind == .image ? "photo" : kind == .link ? "link" : "text.alignleft" }
    var image: NSImage? { imageData.flatMap(NSImage.init(data:)) }
    var provider: NSItemProvider {
        if let image { return NSItemProvider(object: image) }
        return NSItemProvider(object: (text ?? "") as NSString)
    }
}

@MainActor final class ClipboardService: ObservableObject {
    @Published private(set) var entries: [ClipboardEntry] = []
    @Published private(set) var enabled: Bool
    @Published private(set) var message: String?
    var onCapture: ((Date) -> Void)?
    private let board: NSPasteboard
    private let defaults: UserDefaults
    private let storage: URL?
    private var lastChange: Int
    private var timer: Timer?
    private let recentLimit = 24
    private let pinLimit = 12
    static let maximumBytes = 4_000_000

    init(preview: Bool = false, board: NSPasteboard = .general, defaults: UserDefaults = .standard, storage: URL? = nil) {
        self.board = board; self.defaults = defaults
        self.storage = preview ? storage : storage ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first?.appendingPathComponent("ISLA/clipboard-pins.json")
        enabled = !preview && defaults.bool(forKey: "clipboard.enabled")
        lastChange = board.changeCount
        if let url = self.storage, let size = try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize, size < Self.maximumBytes * pinLimit * 2,
           let data = try? Data(contentsOf: url), let saved = try? JSONDecoder().decode([ClipboardEntry].self, from: data) {
            entries = Array(saved.filter { $0.pinned && ($0.imageData?.count ?? 0) <= Self.maximumBytes && ($0.text?.utf8.count ?? 0) <= Self.maximumBytes }.prefix(pinLimit))
        }
    }
    var sorted: [ClipboardEntry] { entries.sorted { $0.pinned != $1.pinned ? $0.pinned : $0.capturedAt > $1.capturedAt } }
    func start() {
        stop()
        let timer = Timer(timeInterval: 0.45, repeats: true) { [weak self] _ in Task { @MainActor in self?.poll() } }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }
    func stop() { timer?.invalidate(); timer = nil }
    func setEnabled(_ value: Bool) {
        enabled = value; defaults.set(value, forKey: "clipboard.enabled")
        lastChange = board.changeCount // Only observe new copies after activation.
        message = nil
    }
    func poll() {
        guard enabled, lastChange != board.changeCount else { return }
        lastChange = board.changeCount
        let types = Set((board.types ?? []).map(\.rawValue))
        let hidden = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        guard types.isDisjoint(with: hidden), !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) else { return }
        let kind: ClipboardEntry.Kind
        let text: String?
        let imageData: Data?
        let payload: Data
        if let data = board.data(forType: .png) ?? board.data(forType: .tiff) {
            guard data.count <= Self.maximumBytes, let image = NSImage(data: data), image.size.width <= 12000, image.size.height <= 12000 else { return }
            kind = .image; imageData = data; text = nil; payload = data
        } else if let value = board.string(forType: .string) ?? board.string(forType: .URL), !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard value.utf8.count <= 30_000 else { return }
            let scheme = URL(string: value)?.scheme?.lowercased()
            kind = ["https", "http"].contains(scheme ?? "") && !value.contains(where: \.isWhitespace) ? .link : .text
            text = value; imageData = nil; payload = Data(value.utf8)
        } else { return }
        let fingerprint = kind.rawValue + ":" + SHA256.hash(data: payload).map { String(format: "%02x", $0) }.joined()
        let now = Date()
        if let index = entries.firstIndex(where: { $0.fingerprint == fingerprint }) { entries[index].capturedAt = now }
        else { entries.insert(ClipboardEntry(id: UUID(), kind: kind, text: text, imageData: imageData, fingerprint: fingerprint, capturedAt: now, pinned: false), at: 0) }
        let keep = Set(entries.filter { !$0.pinned }.sorted { $0.capturedAt > $1.capturedAt }.prefix(recentLimit).map(\.id))
        entries.removeAll { !$0.pinned && !keep.contains($0.id) }
        message = nil
        onCapture?(now)
    }
    func copy(_ item: ClipboardEntry) {
        board.clearContents()
        let ok: Bool
        if let image = item.image { ok = board.writeObjects([image]) }
        else { ok = board.setString(item.text ?? "", forType: .string) }
        lastChange = board.changeCount
        message = ok ? "Copiado. Pégalo donde lo necesites." : "No se pudo copiar."
    }
    func togglePin(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        guard entries[index].pinned || entries.filter(\.pinned).count < pinLimit else { message = "Puedes fijar hasta 12 elementos."; return }
        entries[index].pinned.toggle()
        persist()
    }
    func remove(_ id: UUID) { entries.removeAll { $0.id == id }; persist() }
    func clearRecent() { entries.removeAll { !$0.pinned }; message = nil }
    private func persist() {
        guard let storage else { return }
        do {
            try FileManager.default.createDirectory(at: storage.deletingLastPathComponent(), withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            let data = try JSONEncoder().encode(entries.filter(\.pinned))
            try data.write(to: storage, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: storage.path)
        } catch { message = "No se pudieron guardar los elementos fijados." }
    }
}
